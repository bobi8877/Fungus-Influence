            <div class="story1">
                <div id="text">
                    <h2>The Last of Us (Part I)</h2>
                    <p>
                        The Last of Us takes place after a fungal infection called Cordyceps collapses civilization and turns many humans into violent infected creatures.
                    </p>
                    <h3>Main setup</h3>
                    <p>
                        The story begins with Joel Miller, a hardened smuggler living in a militarized quarantine zone. Twenty years earlier, during the outbreak, his daughter Sarah was killed by a soldier while they tried to escape chaos. That trauma defines the rest of his life.
                        <br><br>
                        Joel is hired to transport a 14-year-old girl named Ellie across the country. Ellie is special because she appears immune to the infection after being bitten.
                        <br><br>
                        The mission comes from the Fireflies, a rebel group hoping to restore society. Joel and Ellie travel through ruined cities, hostile survivor groups, and infected zones. Along the way, their relationship changes from reluctant partners into a father-daughter bond.
                    </p>
                    <h3>Key journey moments</h3>
                    <ul>
                        <li>Joel slowly opens up emotionally after years of emotional numbness.</li>
                        <li>Ellie becomes tougher and more independent as she experiences loss and violence.</li>
                        <li>They meet allies like Tess, Bill, Henry, and Sam, many of whom die tragically.</li>
                        <li>Joel is seriously injured during winter, forcing Ellie to survive on her own for a time.</li>
                        <li>Ellie is captured by a cannibalistic leader named David, whom she eventually kills in self-defense.</li>
                    </ul>
                    <h3>Ending</h3>
                    <p>Joel finally delivers Ellie to the Fireflies in Salt Lake City. However, he learns the doctors plan to remove the mutated Cordyceps in Ellie’s brain to create a possible vaccine — a surgery that will kill her.
                        <br><br>
                        Unable to lose another daughter figure, Joel massacres the Fireflies and rescues Ellie. He kills the lead surgeon and lies to Ellie afterward, telling her the Fireflies had stopped searching for a cure and that there were many other immune people.
                        <br><br>
                        The ending centers on love, selfishness, survival, and whether Joel’s choice saved Ellie or doomed humanity.
                    </p>
