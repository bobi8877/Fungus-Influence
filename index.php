                    <h2>The Last of Us Part II</h2>
                    <p>
                        The Last of Us Part II takes place about five years later. Joel and Ellie now live in Jackson, Wyoming, a relatively safe settlement. Their relationship has become strained because Ellie suspects Joel lied about what happened at the hospital.
                    </p>
                    <h3>Joel’s death</h3>
                    <p>
                        Early in the game, Joel and his brother Tommy rescue a young woman named Abby from infected. Abby then reveals she belongs to a group seeking revenge.
                        <br><br>
                        Abby brutally kills Joel in front of Ellie.
                        <br><br>
                        The reason: Abby’s father was the Firefly surgeon Joel killed while rescuing Ellie in the first game.
                        <br><br>
                        Joel’s death becomes the emotional core of Part II.
                    </p>
                    <h3>Ellie’s revenge journey</h3>
                    <p>
                        Ellie travels to Seattle with her girlfriend Dina to hunt Abby and her companions. Over several days, Ellie kills many members of Abby’s group, becoming increasingly traumatized and morally compromised.
                        <br><br>
                        The game then shifts perspective halfway through and retells those same days from Abby’s point of view.
                    </p>
                    <h3>Abby’s side</h3>
                    <p>
                        Abby is shown not as a villain, but as another damaged survivor shaped by grief. She belongs to the Washington Liberation Front (WLF), which is fighting a religious faction called the Seraphites.
                        <br><br>
                        Abby eventually protects two runaway Seraphite siblings, Lev and Yara. Through them, she begins rediscovering empathy and purpose, much like Joel did with Ellie.
                    </p>
                    <h3>Final confrontation</h3>
                    <p>
                        Ellie and Abby eventually confront each other multiple times, causing devastating losses on both sides.
                        <br><br>
                        Later, Ellie tries to settle into peaceful life with Dina and their baby, but PTSD and Joel’s death still haunt her. She leaves to pursue Abby one last time.
                        <br><br>
                        Ellie finds Abby imprisoned and tortured by a slaver group called the Rattlers. After freeing her, Ellie still forces a final fight.
                        <br><br>
                        At the last moment, Ellie remembers a final conversation with Joel where she had been willing to try forgiving him. Realizing revenge will not heal her pain, Ellie lets Abby go.
                    </p>
                    <h3>Ending</h3>
                    <p>
                        Ellie returns home to find Dina gone. She has lost Joel, her relationship, and even two fingers during the fight, making it impossible to properly play Joel’s guitar — a symbol of their bond.
                        <br><br>
                        The story ends ambiguously, focused on grief, revenge, forgiveness, and the cost of violence.
                    </p>
