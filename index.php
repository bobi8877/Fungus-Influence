            <h1>The Characters</h1>
            <div id="text">
                <div class="char">
                    <img src="char/joelchar.jpg" alt="">
                    <h3>
                        Joel Miller
                    </h3>
                    <p>
                        Joel is a Texas-born survivor who lost his daughter Sarah on the night of the initial Cordyceps outbreak, an event that permanently hardened him and stripped away much of his humanity. He spends the next twenty years doing whatever it takes to survive, including working as a smuggler in the Boston quarantine zone alongside Tess. When tasked with escorting Ellie across the country, he initially treats it as just another job, but gradually develops a fierce paternal love for her. At the end of Part I, he makes a morally devastating choice to save Ellie's life at the cost of humanity's chance at a cure, a decision that defines both games. In Part II, the consequences of that choice catch up with him in brutal fashion.
                    </p>
                </div>
                <div class="char">
                    <img src="char/elliechar.jpg" alt="">
                    <h3>
                        Ellie Williams
                    </h3>
                    <p>
                        Ellie is a sharp-tongued, fiercely loyal, and deeply curious teenager who was bitten by an infected but never turned — making her the only known person immune to the Cordyceps fungus. Orphaned young and raised in a military boarding school called FEDRA, she carries a lot of pain beneath her tough exterior and dark humor. Her bond with Joel becomes the emotional core of the first game, filling a void neither of them fully admits to. In Part II, Ellie is older and more haunted, driven by grief and a thirst for vengeance that threatens to consume everything she loves. Her arc across both games is ultimately about the cycle of trauma, love, and the cost of the choices we make for the people we care about.
                    </p>
                </div>
                <div class="char">
                    <img src="char/tesschar.jpg" alt="">
                    <h3>
                        Tess
                    </h3>
                    <p>
                        Tess is Joel's no-nonsense smuggling partner in the Boston quarantine zone, and one of the most respected — and feared — operators in the black market. She is pragmatic, tough, and deeply trusted by Joel, suggesting they share a long and complicated history together. When she discovers she has been bitten during a mission gone wrong, she makes the selfless decision to buy Joel and Ellie time to escape, sacrificing herself to Firefly soldiers and infected alike. Though her screen time is brief, her death is the catalyst that sets the entire journey in motion, and she carries real moral weight despite her short appearance.
                    </p>
                </div>
                <div class="char">
                    <img src="char/marlenechar.jpeg" alt="">
                    <h3>
                        Marlene
                    </h3>
                    <p>
                        Marlene is the leader of the Fireflies, the rebel militia fighting against FEDRA's authoritarian control of the quarantine zones. She has a deep personal connection to Ellie, having made a promise to Ellie's mother Anna to look after her daughter before Anna died. Despite genuinely caring for Ellie, Marlene is willing to sacrifice her life for what she believes is the greater good — using Ellie's brain to develop a Cordyceps vaccine. She represents a tragic kind of idealism, someone whose good intentions lead her to make ruthless decisions. Her death at Joel's hands at the end of Part I is one of the most morally complex moments in the series.
                    </p>
                </div>
                <div class="char">
                    <img src="char/tommillerchar.jpg" alt="">
                    <h3>
                        Tommy Miller
                    </h3>
                    <p>
                        Tommy is Joel's younger brother, a former Firefly who eventually settled down in Jackson, Wyoming, where he helped build one of the most functional and humane survivor communities in the country. He is warmer and more optimistic than Joel, representing the possibility that people can hold onto their decency even in a broken world. In Part I, he serves as a destination and a brief moral mirror for Joel, highlighting how differently the two brothers responded to the same tragedy. In Part II, Tommy is dragged back into violence by grief, and his obsession with revenge takes a serious toll on him and those around him, showing that even the more hopeful characters are not immune to the cycle of loss and retaliation.
                    </p>
                </div>
                <div class="char">
                    <img src="char/abbychar.jpg" alt="">
                    <h3>Abby</h3>
                    <p>
                        Abby is introduced as an antagonist in Part II but gradually becomes one of the most complex characters in the entire series. She is a physically formidable soldier connected to the Fireflies whose deeply personal motivations for her actions are revealed slowly and deliberately by the story. The game forces players to spend significant time in her perspective, showing her friendships, her loyalties, and her own capacity for both violence and compassion. Her storyline directly mirrors Ellie's in thematic terms, exploring how grief and love can drive people to terrible places. She is a polarizing character by design, and her arc is central to the game's message about empathy and the human cost of cycles of revenge.
                    </p>
                </div>
                <div class="char">
                    <img src="char/dinachar.jpg" alt="">
                    <h3>
                        Dina
                    </h3>
                    <p>
                        Dina is Ellie's girlfriend and one of the brightest emotional presences in Part II, bringing warmth, humor, and a grounded sense of love to a story filled with darkness. She is quick-witted and brave, choosing to follow Ellie into Seattle despite the enormous dangers involved. Her relationship with Ellie feels genuine and lived-in, and she serves as a reminder of what Ellie is putting at risk by pursuing revenge. As the story progresses, the tension between Dina's desire for a peaceful life and Ellie's obsession becomes one of the game's most heartbreaking threads.
                    </p>
                </div>
                <div class="char">
                    <img src="char/jessechar.jpg" alt="">
                    <h3>
                        Jesse
                    </h3>
                    <p>
                        Jesse is a dependable and well-liked member of the Jackson community, known for being level-headed in situations where others might panic. He joins Ellie and Dina in Seattle out of loyalty and love, even when it puts him in serious danger. He often acts as the voice of reason in the group, pushing back against recklessness and trying to keep everyone grounded. His presence adds a sense of stability and camaraderie to the Seattle sections of Part II, which makes the events surrounding him hit all the harder when the story takes its darkest turns.
                    </p>
                </div>
